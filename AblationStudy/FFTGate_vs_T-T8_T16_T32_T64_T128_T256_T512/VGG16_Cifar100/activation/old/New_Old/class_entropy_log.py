import os
import torch

def log_per_class_entropy(activations, targets, epoch):
    num_classes = 10  # Adjust if needed (CIFAR-10 = 10 classes)

    class_entropies = {}
    for class_id in range(num_classes):
        class_mask = (targets == class_id)
        if class_mask.sum() == 0:
            continue

        class_activations = activations[class_mask]
        class_magnitudes = class_activations.abs().mean(dim=[0, 2, 3])
        p = class_magnitudes / class_magnitudes.sum()

        class_entropy = -(p * torch.log(p + 1e-6)).sum()
        class_entropies[class_id] = class_entropy.item()

    # 🔴 Define the full path directly (Windows format)
    log_folder = r"C:\Users\emeka\Research\ModelCUDA\Big_Data_Journal\Comparison\Code\CIFAR10\Results\MY"
    log_file_path = os.path.join(log_folder, "class_entropy_log.txt")

    # 🔴 Ensure folder exists
    os.makedirs(log_folder, exist_ok=True)

    # 🔴 Refresh the file (clear it) at the start of each session or before each epoch if you want
    if epoch == 0:  # Optionally only clear at epoch 0
        if os.path.exists(log_file_path):
            os.remove(log_file_path)  # This deletes the file

    # 🔴 Open the log file in append mode to avoid overwriting previous entries after refresh
    with open(log_file_path, "a") as f:
        f.write(f"🔎 Epoch {epoch} Per-Class Activation Entropy: {class_entropies}\n")

    # ✅ Confirmation print
    print(f"✅ [LOG] Per-Class Activation Entropy written to: {log_file_path}")

    # Optional: print the actual entropies to console too
    print(f"🔎 Epoch {epoch} Per-Class Activation Entropy: {class_entropies}")




